// The shared preference contains only the name of the selected reading lens.
const EssayReadingLens = (() => {
  const key = 'uzel-reading-lens-v1';
  const valid = value => value === 'orthodox' || value === 'secular';
  const label = mode => mode === 'orthodox' ? 'Православный ракурс' : 'Общелитературный разбор';
  let active = 'secular';
  function restore(previous) {
    let shared;
    try { shared = localStorage.getItem(key); } catch {}
    active = valid(shared) ? shared : valid(previous) ? previous : 'secular';
    return active;
  }
  function select(mode, announce = true) {
    if (!valid(mode)) return;
    active = mode;
    if (!announce) return;
    try { localStorage.setItem(key, mode); } catch {}
    window.dispatchEvent(new CustomEvent('uzel-reading-lens', {detail:{mode}}));
  }

  // Each intervention keeps the writing operation (verify, explain, revise)
  // and asks for evidence. It does not prescribe a belief or a verdict.
  const prompts = {
    topic: ['Какие слова темы задают границу того, что предстоит объяснить на примере?', 'Какой нравственный вопрос можно услышать в этой теме и какое слово темы удерживает тебя от слишком широкого ответа?'],
    thesis: ['Какое утверждение о выборе героя ты готов защищать, опираясь на сцену?', 'Если посмотреть на выбор глазами того, кого он затронул, какую мысль об ответственности можно проверить по тексту?'],
    episode: ['Какая реплика или деталь позволяет заметить, что меняется между участниками сцены?', 'В какой реплике или паузе можно увидеть внимание к ближнему либо его отсутствие?'],
    retell: ['Как изменится смысл сцены, если убрать одну из рассказанных тобой подробностей?', 'Какое действие заметно меняет положение другого человека и что это даёт для разговора о милосердии?'],
    motive: ['По каким словам или поступкам видно, что у героя мог быть именно такой мотив?', 'Если тебе видится сострадание или гордость, какое действие поддерживает такое прочтение и насколько уверенно о нём можно говорить?'],
    quote: ['Кому принадлежит реплика по тексту и как её окружение помогает понять сцену?', 'Какие слова действительно произносит герой, а где начинается твоё нравственное толкование этих слов?'],
    link: ['Какой вывод о герое можно проверить именно по этой детали?', 'Как выбранная подробность помогает обсудить совесть, свободу или ответственность героя перед другим человеком? Выбери только то, для чего есть основание в тексте.'],
    transition: ['Какая мысль следующего абзаца вырастает из уже названной детали?', 'Как перейти от поступка к его последствиям для ближнего, сохранив связь между двумя абзацами?'],
    ending: ['Как сцена уточняет твой первый ответ на вопрос темы?', 'Чей опыт в этой сцене заставляет точнее сформулировать твою мысль о добре или о причинённом вреде?'],
    precision: ['Какое оценочное слово можно проверить действием героя?', 'Не вынесена ли оценка человеку целиком там, где ты можешь судить лишь об одном поступке? Какая деталь поможет уточнить фразу?'],
    alternative: ['Какая деталь допускает ещё одно объяснение поступка?', 'Можно ли иначе понять меру ответственности героя, если принять во внимание слова другого участника сцены?'],
    draft: ['В какой фразе читатель видит связь между деталью и твоим выводом?', 'Какое место черновика помогает понять нравственный выбор героя, позволяя читателю проверить твоё прочтение по тексту?'],
    review: ['Какую фразу ты бы попросил читателя проверить по сцене, прежде чем соглашаться с выводом?', 'В каком месте ты различаешь поступок героя и своё суждение о нём? Что можно проверить по произведению?'],
    shelf: ['Как сохранённое наблюдение может стать доводом к одной из твоих тем?', 'Какое слово или действие в твоей записи поможет обсудить отношение к ближнему, сохраняя право героя на иную трактовку?'],
    paragraphTrial: ['Что в просьбе Миши о поправке указывает на важное ему различие между личным и публичным исправлением?', 'Как просьба Миши о поправке помогает обсудить правду и ответственность перед теми, кто уже прочитал заметку?'],
    rehearsal: ['Как после самостоятельной работы ты проверишь, что из сцены действительно следует твой вывод?', 'Когда закончишь, какую деталь ты перечитаешь, чтобы проверить своё понимание нравственного выбора героя?']
  };
  function question(stage, mode = active) {
    return (prompts[stage] || prompts.link)[mode === 'orthodox' ? 1 : 0];
  }
  // The recommended scene for a theme can differ from the book’s main card.
  // Its question must not mention an episode or character from another card.
  function routeQuestion(route, book, topic) {
    if (!route.scene || route.scene === book.fact) return book.orthodox;
    const subject = (topic + ' ' + route.why).toLowerCase().replace(/ё/g, 'е');
    if (/природ|земл[яеию]|окружающ.{0,5}мир/u.test(subject))
      return 'Какая подробность пейзажа или действие человека позволяет говорить о благодарности за мир или о бережном отношении к нему?';
    if (/искусств|музык|творчеств|талант|поэзи/u.test(subject))
      return 'Что происходит с вниманием человека к себе или к другому при встрече с искусством? По какой детали это видно?';
    if (/памят|поколен|семь|родител|матер|родин/u.test(subject))
      return 'Как в этой сцене проявляется или прерывается связь с теми, кому человек обязан заботой? На какой поступок можно сослаться?';
    if (/прощ|обид|отомст|месть|вражд|примир/u.test(subject))
      return 'В какой момент у человека появляется возможность ответить на обиду иначе и что он с этой возможностью делает?';
    if (/совест|стыд|честност|правд|вин[ауеы]|ошибк/u.test(subject))
      return 'Какой поступок или реплика позволяет обсуждать совесть героя? Что о его внутреннем решении ещё остаётся неизвестным?';
    if (/друг|верност|обещан|предат|присяг/u.test(subject))
      return 'Как герой отвечает за своё слово перед другим человеком и какая деталь даёт основание так его понять?';
    return question('episode', 'orthodox');
  }
  function detail(stage) {
    return '<details class="ew-reading-question" data-ew-lens-question="' + stage + '"><summary>' + label(active) +
      ' · вопрос к тексту</summary><p>' + question(stage) + '</p></details>';
  }
  function refresh(container) {
    for (const block of container.querySelectorAll('[data-ew-lens-question]')) {
      block.querySelector('summary').textContent = label(active) + ' · вопрос к тексту';
      block.querySelector('p').textContent = question(block.dataset.ewLensQuestion);
    }
  }
  return {key, valid, label, restore, select, question, routeQuestion, detail, refresh, current:() => active};
})();
