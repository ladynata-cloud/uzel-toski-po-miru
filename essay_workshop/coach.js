const EssayCoach = (() => {
  function countWords(text = '') {
    // Combine initials and a surname before tokenizing. Either order is common.
    const initials = String.raw`(?:\p{Lu}\.\s*){1,3}`;
    const surname = String.raw`\p{Lu}\p{Ll}+(?:[-‐‑]\p{Lu}\p{Ll}+)*`;
    let input = String(text ?? '').normalize('NFC');
    input = input.replace(new RegExp(`(?<!\\p{L})${initials}(${surname})(?!\\p{L})`, 'gu'), '$1');
    input = input.replace(new RegExp(`(?<!\\p{L})(${surname})\\s+${initials}(?!\\p{L})`, 'gu'), '$1 ');
    return (input.match(/\p{L}[\p{L}\p{M}]*(?:[-‐‑’']\p{L}[\p{L}\p{M}]*)*/gu) || []).length;
  }

  function normalized(value) {
    return String(value ?? '').toLocaleLowerCase('ru').replace(/ё/g, 'е')
      .replace(/[^\p{L}\p{N}]+/gu, ' ').trim();
  }

  // Echo a short student phrase so the revision has a specific starting point.
  function excerpt(value) {
    const words = String(value ?? '').trim().split(/\s+/);
    return '«' + words.slice(0, 14).join(' ') + (words.length > 14 ? '…' : '') + '»';
  }

  function readingQuestion(work, mode) {
    const question = mode === 'orthodox' ? work?.orthodox : work?.secular;
    if (question) return question;
    return mode === 'orthodox'
      ? 'Если тебе близок православный взгляд, какое слово или действие героя позволяет так прочесть эту сцену?'
      : 'Какая деталь в этой сцене помогла тебе понять героя?';
  }

  function thesisHint({topic, thesis, work, mode, reason}) {
    const question = topic ? 'Перечитай тему ' + excerpt(topic) + '. ' : '';
    if (thesis && normalized(thesis) === normalized(topic)) {
      return 'Пока здесь сама формулировка темы. Как бы ты ответил на неё человеку, который спросил твоего мнения? Запиши один ответ своими словами.';
    }
    if (reason === 'retell') {
      return 'На минуту отложи книгу. Если убрать имена героев и события, какая твоя мысль об этой теме останется? Запиши её одной фразой.';
    }
    if (reason === 'clarify') {
      return question + 'Какое слово в теме можно понять по-разному? Объясни другу, в каком смысле ты будешь его употреблять.';
    }
    if (reason === 'stuck' || !thesis) {
      const start = work?.title
        ? 'Вспомни один поступок из произведения ' + excerpt(work.title) + '. Что он помог тебе понять о вопросе темы?'
        : 'Вспомни случай из прочитанной книги, когда ты согласился с героем или поспорил с ним. Как этот случай помогает ответить на вопрос темы?';
      return question + start;
    }
    if (/\?\s*$/u.test(thesis)) {
      return 'Прочитай свой вопрос вслух и дай на него короткий ответ. Какую часть этого ответа можно будет отстоять примером из книги?';
    }
    if (countWords(thesis) <= 4 || /^(?:(?:это|очень|важно|нужно|всегда|надо|быть|добрым|поступать|хорошо|по совести)\s*)+$/u.test(normalized(thesis))) {
      return 'Уточни мысль ' + excerpt(thesis) + '. При каких обстоятельствах она верна и почему? Выбери одно уточнение, которое тебе поможет показать эпизод.';
    }
    if (reason === 'check') {
      return question + 'Прочитай свой тезис как ответ на этот вопрос. Где именно в ответе видна твоя позиция? Если осталась только общая фраза, добавь, почему ты так считаешь.';
    }
    return mode === 'orthodox'
      ? 'Вернись к своей мысли ' + excerpt(thesis) + '. Как бы ты пояснил её читателю с другим взглядом на веру, опираясь на поступок персонажа?'
      : 'Представь, что читатель спросил: «Всегда ли это так?» Какой случай из книги поможет тебе уточнить свою мысль?';
  }

  function episodeHint({episode, work, mode, reason}) {
    const question = readingQuestion(work, mode);
    if (reason === 'retell') {
      return 'Оставь одно действие, без которого твой довод развалится. Остальные события временно убери. ' + question;
    }
    if (reason === 'check') {
      return episode
        ? 'Найди описанную сцену в книге. Совпадают ли персонаж и его поступок с тем, что ты записал? Если приводишь точные слова, сверь их с текстом.'
        : 'Запиши, кто что сделал в выбранной сцене, затем сверь одну деталь с текстом.';
    }
    if (reason === 'clarify') return question;
    if (reason === 'stuck' || !episode) {
      return work?.fact
        ? 'Опора для памяти. ' + work.fact + ' Какую одну деталь из этого эпизода ты возьмёшь для своего рассуждения? Запиши её своими словами.'
        : 'Открой книгу на знакомой сцене. Запиши, кто оказался перед выбором и что конкретно сделал. Одного поступка достаточно для этого шага.';
    }
    return 'Прочитай свой фрагмент ' + excerpt(episode) + '. ' + question;
  }

  function linkHint({link, thesis, episode, work, mode, reason}) {
    if (reason === 'retell' || (link && normalized(link) === normalized(episode))) {
      return 'Представь, что читатель уже знает сюжет. Какой вывод он может сделать именно из выбранной детали? Покажи, как этот вывод отвечает на вопрос темы.';
    }
    if (link && normalized(link) === normalized(thesis)) {
      return 'Ты вернулся к формулировке тезиса. Выбери одно слово или действие из сцены и объясни, почему оно убеждает тебя в этой мысли.';
    }
    if (reason === 'clarify') {
      return readingQuestion(work, mode) + ' Как твой ответ связан с тем, что ты утверждаешь в тезисе?';
    }
    if (reason === 'check') {
      return 'Мысленно убери литературный эпизод. Если довод можно без изменений отнести к любой книге, уточни его одной деталью именно этой сцены.';
    }
    if (!episode) return 'Вернись к шагу с эпизодом и назови один поступок или реплику персонажа. Тогда появится деталь, от которой можно вести рассуждение.';
    if (!thesis) return 'Как бы ты ответил на вопрос темы одним предложением? Запиши этот ответ в поле тезиса и вернись к выбранной сцене.';
    if (!link || reason === 'stuck') {
      return 'Твоя мысль начинается так: ' + excerpt(thesis) + '. Что в выбранном эпизоде даёт тебе основание так думать? Начни с детали, которая кажется решающей.';
    }
    return 'Проверь переход между эпизодом и мыслью. Если бы персонаж в той же сцене поступил иначе, изменился бы твой вывод? Объясни почему.';
  }

  function draftHint({draft, topic, reason}) {
    const total = countWords(draft);
    if (!total) {
      return 'Открой свои записи о тезисе и эпизоде. Запиши начало сочинения своими словами, затем перейди к сцене, которая помогла тебе так ответить.';
    }
    if (reason === 'retell') {
      return 'Найди самый длинный пересказ событий. Какие две детали действительно нужны твоему рассуждению? Прочитай абзац с этими деталями и добавь своё объяснение.';
    }
    if (reason === 'clarify') {
      return 'Выбери фразу, о которую спотыкаешься при чтении вслух. Кто в ней действует и что делает? Вырази эту мысль короче и проверь, сохранился ли смысл.';
    }
    if (reason === 'stuck') {
      return 'Перечитай последнее написанное предложение. Какой вопрос после него задал бы читатель? Ответ запиши в следующем предложении.';
    }
    if (total < 250) {
      const missing = 250 - total;
      const wordForm = {one:'слово', few:'слова', many:'слов', other:'слова'}[new Intl.PluralRules('ru').select(missing)];
      return 'До минимального объёма осталось примерно ' + missing + ' ' + wordForm + '. Найди место, где упомянут поступок героя. Что изменилось благодаря этому поступку и как это помогает доказать твою мысль?';
    }
    const reread = topic ? 'Прочитай тему ' + excerpt(topic) + ' и свой вывод подряд.' : 'Прочитай вопрос темы и свой вывод подряд.';
    if (total < 350) {
      return 'По счётчику минимум в 250 слов достигнут. Ориентир ФИПИ — от 350. ' + reread + ' Какую часть ответа стоит развить на примере из книги?';
    }
    return reread + ' Затем найди в середине сочинения место, где ты объясняешь связь эпизода с этим ответом. Прочитай переход вслух.';
  }

  const stages = {thesis: thesisHint, episode: episodeHint, link: linkHint, draft: draftHint};

  function advise(context = {}) {
    const input = {...context};
    for (const key of ['topic', 'thesis', 'episode', 'link', 'draft']) {
      input[key] = String(input[key] ?? '').trim();
    }
    const handler = Object.hasOwn(stages, input.stage) ? stages[input.stage] : thesisHint;
    return handler(input);
  }

  const conversationSteps = {
    thesis: [
      'Какой конкретный поступок героя помог тебе прийти к этой мысли?',
      'Теперь попробуй соединить этот поступок со своей мыслью одним предложением. Почему он для неё важен?',
      'Запиши свой ответ в поле тезиса. На следующем шаге можно будет подобрать точную деталь из книги.'
    ],
    episode: [
      'Какое слово, жест или решение персонажа здесь особенно важно для твоего рассуждения?',
      'Представь, что автор убрал именно эту деталь. Что читателю стало бы труднее понять?',
      'Сохрани описание сцены в поле эпизода. На шаге со связью ты сможешь объяснить, как эта сцена поддерживает твой тезис.'
    ],
    link: [
      'Как эта деталь помогает ответить именно на вопрос темы? Попробуй закончить мысль своими словами.',
      'Какое слово из твоего тезиса ты теперь можешь объяснить точнее благодаря этой детали?',
      'Перенеси своё объяснение в поле связи с тезисом. Прочитай эпизод и объяснение подряд.'
    ],
    draft: [
      'Какое предложение в твоём тексте объясняет читателю, почему выбранная сцена важна? Приведи его здесь.',
      'Перечитай переход к этому предложению. Какой вопрос читателя оно снимает?',
      'Внеси уточнение в черновик и прочитай этот абзац вслух. Где стоит сделать паузу?'
    ]
  };

  const smallerSteps = {
    thesis: 'Попробуй ответить вслух как близкому другу. Пришли первые три-четыре слова своего ответа. На этом шаге их хватит.',
    episode: 'Назови только два слова из сцены: имя персонажа и глагол, который описывает его действие.',
    link: 'Выбери одну деталь из сцены, которую ты бы сохранил в очень коротком пересказе. Что потеряется, если её убрать?',
    draft: 'Прочитай один абзац и выбери одно предложение, которое хочется изменить. Пришли только его и скажи, что тебя смущает.'
  };

  function intentFeedback(label, context) {
    const {topic, thesis, episode, work, mode} = context;
    switch (label) {
      case 'thesis':
        return thesis?.trim()
          ? 'Вернись к своей фразе ' + excerpt(thesis) + '. Какую причину или границу ты мог бы добавить, чтобы ответ на тему стал точнее?'
          : 'Скажи вслух, что ты ответил бы другу на вопрос ' + excerpt(topic || 'темы') + '. Запиши сначала одно предложение.';
      case 'scene':
        return work?.fact
          ? 'Вспомни сцену. ' + work.fact + ' Какую одну деталь ты сможешь проверить по тексту и объяснить своими словами?'
          : 'Открой рассказ или главу, которую помнишь. В каком месте герой решает, как поступить? Выпиши одно действие.';
      case 'explain':
        return episode?.trim()
          ? 'Ты описываешь сцену так: ' + excerpt(episode) + '. Если убрать одну важную деталь, какой вывод о герое уже нельзя будет сделать?'
          : 'Выбери один поступок героя и представь, что он поступил иначе. Как изменилась бы твоя мысль о нём?';
      case 'wording':
        return 'Выдели в своём тексте одно предложение, которое трудно прочитать вслух, и нажми «Разобрать фразу». Какой смысл в нём важно сохранить, даже если убрать половину слов?';
      case 'counter':
        return mode === 'orthodox'
          ? 'Представь другую трактовку этого же поступка. Какая деталь поддерживает именно твоё прочтение и допускает ли она другое объяснение?'
          : 'Представь читателя, который иначе объясняет поступок героя. Какое слово в своём выводе ты бы уточнил, чтобы учесть его возражение?';
      default: return '';
    }
  }

  function reply(context = {}, message = '', previousTurn = null) {
    const raw = String(message ?? '').trim();
    const words = normalized(raw);
    const stage = Object.hasOwn(stages, context.stage) ? context.stage : 'thesis';
    if (!words) return 'Напиши, на чём ты остановился. Можно прислать одну свою фразу или задать вопрос о сочинении.';

    const asks = raw.includes('?') || /^(?:а |так |подскажи |скажи )*(?:можно|сколько|надо ли|нужно ли|обязательно ли|хватит|достаточно|правда ли|как|что|кто|почему|где|разве|како)/u.test(words);
    const previousUser = normalized(previousTurn?.user);
    const previousReply = String(previousTurn?.assistant ?? '');
    const repeated = words === previousUser || (previousUser && words === 'все еще ' + previousUser);

    if (/слов|объем|минимум/u.test(words) && (/минимум|сколько слов|объем|порог|250|350/u.test(words) || (asks && /\d+ слов/u.test(words)))) {
      const size = countWords(context.draft);
      const detail = size ? ' В твоём черновике по этому счётчику примерно ' + size + '.' : '';
      return 'Минимум для итогового сочинения — 250 слов. ФИПИ рекомендует писать от 350. При объёме 250–349 слов работу допускают к дальнейшей проверке. Максимальный объём не установлен.' + detail;
    }

    if (/(?:^| )(?:библи[яиюей]|евангел[а-я]*|писани[еяию]|священн[а-я]* писани[а-я]*)(?: |$)/u.test(words) && /аргумент|пример|можно ли|подойдет|достаточно|источник/u.test(words)) {
      return 'По разъяснению ФИПИ Библию можно взять как самостоятельный литературный источник. Выбери эпизод, назови книгу и покажи, как поступок или слова персонажа помогают обосновать твой ответ на тему.';
    }

    if (/(?:дв[аеух]|два|две|втор|одн|один|количеств|сколько|\d+).*?(?:книг|книж|литературн|аргумент|пример|произведени|текст)|(?:книг|аргумент|произведени|пример).*?(?:дв[аеух]|сколько)/u.test(words) && (asks || /обязательн|требую|нуж(?:но|ны|на)|хватит/u.test(words))) {
      return 'Достаточно одного опубликованного произведения. Выбери из него эпизод, который действительно помогает обосновать твою мысль. ' + (repeated ? 'Какую сцену из этой книги ты лучше всего помнишь?' : 'Как поступок героя связан с темой?');
    }

    if (/(?:напиши|сделай|пришли|сочини|дай|выдай|сгенерируй|нуж[неаоы]+) (?:.{1,40} )?(?:сочинение|готов[а-я]+ (?:текст|сочинение|абзац|ответ|тезис))|готов[а-я]+ сочинение (?:целиком|за меня)/u.test(words)) {
      return 'Сочинение на экзамене пишешь ты. Давай начнём с твоей мысли. ' + (repeated ? smallerSteps.thesis : advise({...context, stage:'thesis', reason:'stuck'}));
    }

    if (/(?:^| )тем(?:а|е|у|ы|ой)?(?: |$)/u.test(words) && /будут|попад[еу]|настоящие|реальные|заранее|на экзамене/u.test(words) && asks) {
      return 'В тренажёре авторские темы для практики. Конкретный комплект на экзамене станет известен в день проведения. Какой вопрос тебе хотелось бы обдумать на знакомой книге?';
    }
    if (/(?:^| )тем(?:а|е|у|ы|ой)?(?: |$)/u.test(words) && /сколько|все темы|одну тему|одной тем/u.test(words) && asks) {
      return 'На итоговом сочинении выбирают одну из шести предложенных тем. Прочитай формулировку целиком: какой вопрос ты будешь раскрывать?';
    }
    if (/(?:^| )тем(?:а|е|у|ы|ой)?(?: |$)/u.test(words) && /выбр|выбир|поня|разобр|смысл|о чем|кака[яю]|какую|что значит|что означает|что от меня/u.test(words) && asks) {
      if (/выбр|выбир/u.test(words)) {
        return 'Прочитай два вопроса из списка. Для какого ты можешь сразу назвать и свой ответ, и сцену из прочитанной книги? Возьми его для первой попытки.';
      }
      const title = context.topic ? 'Твоя тема — ' + excerpt(context.topic) + '. ' : 'Посмотри на формулировку выбранной темы. ';
      return title + 'Представь, что ты задаёшь этот вопрос другу. Какими словами ты бы его переформулировал?';
    }

    if (/тезис/u.test(words) && /что такое|что значит|это что/u.test(words)) {
      return 'Тезис — твой ответ на вопрос темы. Его предстоит обосновать. Как бы ты сформулировал своё мнение одним предложением?';
    }
    if (/без религи|без веры|без православ|не хочу.*(?:религи|веру|православ)|светск|я (?:неверующ|не верю)/u.test(words) && /можно|хочу|давай|переключ|я (?:неверующ|не верю)/u.test(words)) {
      return 'Можно работать в светском ракурсе. Выбери его в переключателе и посмотри на мотив или последствия поступка героя. ' + readingQuestion(context.work, 'secular');
    }
    if (/православ|христианск/u.test(words) && /можно|хочу|давай|переключ/u.test(words)) {
      return 'Выбери православный ракурс в переключателе. ' + readingQuestion(context.work, 'orthodox');
    }

    if (/зачет|оценк|проверь|сколько баллов/u.test(words) && (asks || /проверь|поставь|оцени/u.test(words))) {
      return 'Результат за экзаменационную работу определяет эксперт. Для самопроверки найди в черновике две фразы: свой ответ на тему и объяснение, почему эпизод его подтверждает. Пришли ту, в которой сомневаешься.';
    }

    // A statement of literary interpretation may be a student's answer, rather than a request.
    const asksForHelp = asks || /помог|подска|не понимаю|не могу|не получа|застр|хоч|трудно|путаю|повторя|только пересказ|сомнева/u.test(words);
    const verifiesFact = /звали|зовут|дослов|в (?:какой|которой) главе|кто (?:именно |это )?сказал|не могу вспомнить,? как/u.test(words);
    if (asksForHelp && !verifiesFact && !repeated && typeof EssayIntent !== 'undefined') {
      const hint = intentFeedback(EssayIntent.classify(raw).label, context);
      if (hint && previousReply !== hint) return hint;
    }

    if ((asks || /не (?:помню|уверен|могу вспомнить)|забыл/u.test(words)) && /цитат|дословно|точн[аоя]|сказал|говорит|произнес|звали|зовут|поступил|поступила|пошел|заплакал|назва|действительно ли|правда ли|в (?:какой|которой) главе|^(?:а )?(?:кто|кому|когда|где|куда|зачем|почему|разве)|(?:какой|какая|какую|что) (?:геро|персонаж|автор)/u.test(words)) {
      const book = context.work?.title ? 'Открой полный текст произведения ' + excerpt(context.work.title) + '. ' : 'Уточни автора и название и открой полный текст выбранного произведения. ';
      return book + (repeated ? 'Прочитай пару предложений до и после спорного места. К кому относится фраза и что происходит сразу после неё?' : 'Найди нужную сцену, проверь, кому принадлежит реплика или поступок. Можно прислать короткий фрагмент с указанием источника или пересказать сцену своими словами.');
    }

    if (/^(?:(?:я|все еще|пока|вообще) )*(?:не знаю|не понимаю|затрудняюсь|застрял|растерял|не получается|помоги)|попроще|поподробнее|по другому/u.test(words)) {
      return repeated || previousReply ? smallerSteps[stage] : advise({...context, stage, reason:'stuck'});
    }
    if (repeated) return smallerSteps[stage];
    if (asks) {
      return 'Уточни, о чём вопрос: о правилах сочинения, о детали из книги или о формулировке твоей мысли? Можно привести одно предложение и указать, что именно в нём вызывает сомнение.';
    }

    const turns = conversationSteps[stage];
    const lastStep = turns.findIndex(step => previousReply.includes(step));
    const nextStep = turns[(lastStep + 1) % turns.length];
    return 'Возьмём твою фразу ' + excerpt(raw) + '. ' + nextStep;
  }

  return Object.freeze({advise, countWords, reply});
})();
