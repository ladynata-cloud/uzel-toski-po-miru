const EssayCoach = (() => {
  function firstDraftLine(text) {
    return String(text ?? '').trimStart().split(/[\r\n]/u, 1)[0].trimEnd();
  }

  function countWords(text = '', draftHeading = '') {
    let input = String(text ?? '').trimStart();
    // An explicitly marked topic heading is separate from the essay. The same
    // words in a paragraph and words in quotations still count.
    if (draftHeading && firstDraftLine(input) === draftHeading) input = input.slice(draftHeading.length);
    input = input.normalize('NFC').replace(/\u00ad/gu, '');
    // Combine initials and a surname before tokenizing. Either order is common.
    const initials = String.raw`(?:\p{Lu}\.(?:[-‐‑]\p{Lu}\.)?\s*){1,3}`;
    const surname = String.raw`\p{Lu}(?:[-‐‑’']?[\p{L}\p{M}])+`;
    input = input.replace(new RegExp(`(?<!\\p{L})${initials}(${surname})(?!\\p{L})`, 'gu'), '$1');
    input = input.replace(new RegExp(`(?<!\\p{L})(${surname})\\s+${initials}(?!\\p{L})`, 'gu'), '$1 ');
    return (input.match(/\p{L}[\p{L}\p{M}]*(?:[-‐‑’']\p{L}[\p{L}\p{M}]*)*/gu) || []).length;
  }

  function normalized(value) {
    return String(value ?? '').toLocaleLowerCase('ru').replace(/ё/g, 'е')
      .replace(/[^\p{L}\p{N}]+/gu, ' ').trim();
  }

  // Echo a short student phrase so the revision has a specific starting point.
  function excerpt(value) {
    const words = String(value ?? '').trim().split(/\s+/);
    return '«' + words.slice(0, 14).join(' ') + (words.length > 14 ? '…' : '') + '»';
  }

  function readingQuestion(work, mode) {
    const question = mode === 'orthodox' ? work?.orthodox : work?.secular;
    if (question) return question;
    return mode === 'orthodox'
      ? 'Если тебе близок православный взгляд, какое слово или действие героя позволяет так прочесть эту сцену?'
      : 'Какая деталь в этой сцене помогла тебе понять героя?';
  }

  function thesisHint({topic, thesis, work, mode, reason}) {
    const question = topic ? 'Перечитай тему ' + excerpt(topic) + '. ' : '';
    if (thesis && normalized(thesis) === normalized(topic)) {
      return 'Пока здесь сама формулировка темы. Как бы ты ответил на неё человеку, который спросил твоего мнения? Запиши один ответ своими словами.';
    }
    if (reason === 'retell') {
      return 'На минуту отложи книгу. Если убрать имена героев и события, какая твоя мысль об этой теме останется? Запиши её одной фразой.';
    }
    if (reason === 'clarify') {
      return question + 'Какое слово в теме можно понять по-разному? Объясни другу, в каком смысле ты будешь его употреблять.';
    }
    if (reason === 'stuck' || !thesis) {
      const start = work?.title
        ? 'Вспомни один поступок из произведения ' + excerpt(work.title) + '. Что он помог тебе понять о вопросе темы?'
        : 'Вспомни случай из прочитанной книги, когда ты согласился с героем или поспорил с ним. Как этот случай помогает ответить на вопрос темы?';
      return question + start;
    }
    if (/\?\s*$/u.test(thesis)) {
      return 'Прочитай свой вопрос вслух и дай на него короткий ответ. Какую часть этого ответа можно будет отстоять примером из книги?';
    }
    if (countWords(thesis) <= 4 || /^(?:(?:это|очень|важно|нужно|всегда|надо|быть|добрым|поступать|хорошо|по совести)\s*)+$/u.test(normalized(thesis))) {
      return 'Уточни мысль ' + excerpt(thesis) + '. При каких обстоятельствах она верна и почему? Выбери одно уточнение, которое тебе поможет показать эпизод.';
    }
    if (reason === 'check') {
      return question + 'Прочитай свой тезис как ответ на этот вопрос. Где именно в ответе видна твоя позиция? Если осталась только общая фраза, добавь, почему ты так считаешь.';
    }
    return mode === 'orthodox'
      ? 'Вернись к своей мысли ' + excerpt(thesis) + '. Как бы ты пояснил её читателю с другим взглядом на веру, опираясь на поступок персонажа?'
      : 'Представь, что читатель спросил: «Всегда ли это так?» Какой случай из книги поможет тебе уточнить свою мысль?';
  }

  function episodeHint({episode, work, mode, reason}) {
    const question = readingQuestion(work, mode);
    if (reason === 'retell') {
      return 'Оставь одно действие, без которого твой довод развалится. Остальные события временно убери. ' + question;
    }
    if (reason === 'check') {
      return episode
        ? 'Найди описанную сцену в книге. Совпадают ли персонаж и его поступок с тем, что ты записал? Если приводишь точные слова, сверь их с текстом.'
        : 'Запиши, кто что сделал в выбранной сцене, затем сверь одну деталь с текстом.';
    }
    if (reason === 'clarify') return question;
    if (reason === 'stuck' || !episode) {
      return work?.fact
        ? 'Опора для памяти. ' + work.fact + ' Какую одну деталь из этого эпизода ты возьмёшь для своего рассуждения? Запиши её своими словами.'
        : 'Открой книгу на знакомой сцене. Запиши, кто оказался перед выбором и что конкретно сделал. Одного поступка достаточно для этого шага.';
    }
    return 'Прочитай свой фрагмент ' + excerpt(episode) + '. ' + question;
  }

  function linkHint({link, thesis, episode, work, mode, reason}) {
    if (reason === 'retell' || (link && normalized(link) === normalized(episode))) {
      return 'Представь, что читатель уже знает сюжет. Какой вывод он может сделать именно из выбранной детали? Покажи, как этот вывод отвечает на вопрос темы.';
    }
    if (link && normalized(link) === normalized(thesis)) {
      return 'Ты вернулся к формулировке тезиса. Выбери одно слово или действие из сцены и объясни, почему оно убеждает тебя в этой мысли.';
    }
    if (reason === 'clarify') {
      return readingQuestion(work, mode) + ' Как твой ответ связан с тем, что ты утверждаешь в тезисе?';
    }
    if (reason === 'check') {
      return 'Мысленно убери литературный эпизод. Если довод можно без изменений отнести к любой книге, уточни его одной деталью именно этой сцены.';
    }
    if (!episode) return 'Вернись к шагу с эпизодом и назови один поступок или реплику персонажа. Тогда появится деталь, от которой можно вести рассуждение.';
    if (!thesis) return 'Как бы ты ответил на вопрос темы одним предложением? Запиши этот ответ в поле тезиса и вернись к выбранной сцене.';
    if (!link || reason === 'stuck') {
      return 'Твоя мысль начинается так: ' + excerpt(thesis) + '. Что в выбранном эпизоде даёт тебе основание так думать? Начни с детали, которая кажется решающей.';
    }
    return 'Проверь переход между эпизодом и мыслью. Если бы персонаж в той же сцене поступил иначе, изменился бы твой вывод? Объясни почему.';
  }

  function draftHint({draft, topic, reason, draftHeading}) {
    const total = countWords(draft, draftHeading);
    if (!total) {
      return 'Открой свои записи о тезисе и эпизоде. Запиши начало сочинения своими словами, затем перейди к сцене, которая помогла тебе так ответить.';
    }
    if (reason === 'retell') {
      return 'Найди самый длинный пересказ событий. Какие две детали действительно нужны твоему рассуждению? Прочитай абзац с этими деталями и добавь своё объяснение.';
    }
    if (reason === 'clarify') {
      return 'Выбери фразу, о которую спотыкаешься при чтении вслух. Кто в ней действует и что делает? Вырази эту мысль короче и проверь, сохранился ли смысл.';
    }
    if (reason === 'stuck') {
      return 'Перечитай последнее написанное предложение. Какой вопрос после него задал бы читатель? Ответ запиши в следующем предложении.';
    }
    if (total < 250) {
      const missing = 250 - total;
      const wordForm = {one:'слово', few:'слова', many:'слов', other:'слова'}[new Intl.PluralRules('ru').select(missing)];
      return 'До минимального объёма осталось примерно ' + missing + ' ' + wordForm + '. Найди место, где упомянут поступок героя. Что изменилось благодаря этому поступку и как это помогает доказать твою мысль?';
    }
    const reread = topic ? 'Прочитай тему ' + excerpt(topic) + ' и свой вывод подряд.' : 'Прочитай вопрос темы и свой вывод подряд.';
    if (total < 350) {
      return 'По счётчику минимум в 250 слов достигнут. Ориентир ФИПИ — от 350. ' + reread + ' Какую часть ответа стоит развить на примере из книги?';
    }
    return reread + ' Затем найди в середине сочинения место, где ты объясняешь связь эпизода с этим ответом. Прочитай переход вслух.';
  }

  const stages = {thesis: thesisHint, episode: episodeHint, link: linkHint, draft: draftHint};

  function advise(context = {}) {
    const input = {...context};
    for (const key of ['topic', 'thesis', 'episode', 'link', 'draft']) {
      input[key] = String(input[key] ?? '').trim();
    }
    const handler = Object.hasOwn(stages, input.stage) ? stages[input.stage] : thesisHint;
    return handler(input);
  }

  const conversationSteps = {
    thesis: [
      'Какой конкретный поступок героя помог тебе прийти к этой мысли?',
      'Теперь попробуй соединить этот поступок со своей мыслью одним предложением. Почему он для неё важен?',
      'Запиши свой ответ в поле тезиса. На следующем шаге можно будет подобрать точную деталь из книги.'
    ],
    episode: [
      'Какое слово, жест или решение персонажа здесь особенно важно для твоего рассуждения?',
      'Представь, что автор убрал именно эту деталь. Что читателю стало бы труднее понять?',
      'Сохрани описание сцены в поле эпизода. На шаге со связью ты сможешь объяснить, как эта сцена поддерживает твой тезис.'
    ],
    link: [
      'Как эта деталь помогает ответить именно на вопрос темы? Попробуй закончить мысль своими словами.',
      'Какое слово из твоего тезиса ты теперь можешь объяснить точнее благодаря этой детали?',
      'Перенеси своё объяснение в поле связи с тезисом. Прочитай эпизод и объяснение подряд.'
    ],
    draft: [
      'Какое предложение в твоём тексте объясняет читателю, почему выбранная сцена важна? Приведи его здесь.',
      'Перечитай переход к этому предложению. Какой вопрос читателя оно снимает?',
      'Внеси уточнение в черновик и прочитай этот абзац вслух. Где стоит сделать паузу?'
    ]
  };

  const smallerSteps = {
    thesis: 'Попробуй ответить вслух как близкому другу. Пришли первые три-четыре слова своего ответа. На этом шаге их хватит.',
    episode: 'Назови только два слова из сцены: имя персонажа и глагол, который описывает его действие.',
    link: 'Выбери одну деталь из сцены, которую ты бы сохранил в очень коротком пересказе. Что потеряется, если её убрать?',
    draft: 'Прочитай один абзац и выбери одно предложение, которое хочется изменить. Пришли только его и скажи, что тебя смущает.'
  };

  function intentFeedback(label, context) {
    const {topic, thesis, episode, work, mode} = context;
    switch (label) {
      case 'thesis':
        return thesis?.trim()
          ? 'Вернись к своей фразе ' + excerpt(thesis) + '. Какую причину или границу ты мог бы добавить, чтобы ответ на тему стал точнее?'
          : 'Скажи вслух, что ты ответил бы другу на вопрос ' + excerpt(topic || 'темы') + '. Запиши сначала одно предложение.';
      case 'scene':
        return work?.fact
          ? 'Вспомни сцену. ' + work.fact + ' Какую одну деталь ты сможешь проверить по тексту и объяснить своими словами?'
          : 'Открой рассказ или главу, которую помнишь. В каком месте герой решает, как поступить? Выпиши одно действие.';
      case 'explain':
        return episode?.trim()
          ? 'Ты описываешь сцену так: ' + excerpt(episode) + '. Если убрать одну важную деталь, какой вывод о герое уже нельзя будет сделать?'
          : 'Выбери один поступок героя и представь, что он поступил иначе. Как изменилась бы твоя мысль о нём?';
      case 'wording':
        return 'Выдели в своём тексте одно предложение, которое трудно прочитать вслух, и нажми «Разобрать фразу». Какой смысл в нём важно сохранить, даже если убрать половину слов?';
      case 'counter':
        return mode === 'orthodox'
          ? 'Представь другую трактовку этого же поступка. Какая деталь поддерживает именно твоё прочтение и допускает ли она другое объяснение?'
          : 'Представь читателя, который иначе объясняет поступок героя. Какое слово в своём выводе ты бы уточнил, чтобы учесть его возражение?';
      default: return '';
    }
  }

  function examGuidance(context, words, previousTurn) {
    const wantsDraft = /(?:напиши|пришли|сочини|покажи|дай|выдай|сгенерируй|сделай|нужен|нужно|нужна) (?:(?:мне|за меня|пожалуйста|целиком|целое|полное|свое|свой|готов[а-я]+|итоговое|пример|образец) )*(?:сочинени[ея]|абзац|вступление|заключение|текст для сдачи|готовый (?:текст|ответ|тезис))(?= |$)/u.test(words);
    const borrowed = /(?:списать|спишу|скопирую|скопировать|переписать|перепишу|выуч[а-я]*|перескажу|возьму|взять|зауч[а-я]*|вставлю|перефразир)/u.test(words)
      && /образец|образца|готов[а-я]* (?:сочинени|текст|ответ|абзац)|чуж[а-я]* (?:текст|фраз|мысл|сочинени|абзац)|(?:из|с) (?:интернет|сайт|сборник)|у (?:друг|подруг)|нейросет|чатбот/u.test(words);
    const asksIndependence = /плагиат|(?:требование|провер[а-я]*|критерий|что (?:такое|значит)) (?:к |на )?самостоятельност|самостоятельност[а-я]* (?:на экзамене|сочинения|написания|работы)|(?:текст|работа|сочинение) (?:будет |считается |сочтут )?самостоятельн/u.test(words);
    if (wantsDraft || borrowed || asksIndependence) {
      const first = 'Сочинение на экзамене пишешь ты. Чужой текст или абзац, списанный или выученный наизусть, нарушает требование самостоятельности.';
      const question = context.topic ? 'Твоя тема — «' + context.topic + '». Как ты сам ответил бы на неё одной фразой?' : 'Как бы ты сам ответил на вопрос темы?';
      return first + ' ' + (borrowed ? 'Отложи образец. ' : '') + question;
    }
    if (/цитир|цитат/u.test(words) && /указ[а-я]* источник|(?:нужна|нужен|нужно|как) (?:ли )?(?:оформ|ссыл|указ)|сколько|разреш|допуска|можно ли (?:взять|привести|цитировать|использовать|вставить)/u.test(words)) {
      return 'Можно привести цитату или передать чужие слова косвенно. Укажи источник в свободной форме. Цитирование по объёму не должно превышать твой собственный текст. После заимствованных слов поясни, какую твою мысль они подтверждают.';
    }
    if (/пословиц|поговорк|личн[а-я]+ (?:истори|опыт)|случа[яй] из (?:моей )?жизни/u.test(words)
      && /хватит|достаточно|вместо|подойдет|можно ли|засчитают|только/u.test(words)) {
      return 'Для литературного аргумента нужен пример из опубликованного произведения. Одной поговорки, пословицы или личной истории для этого мало. Вспомни книгу, где герой столкнулся с похожим выбором. Как он поступил?';
    }

    const quantity = words.match(/(?:^| )(\d{1,6}) слов(?:о|а)?(?= |$)/u);
    const fullQuantity = words.match(/(?:во? (?:готовой|полной|всей|итоговой) работе|во? (?:готовом|полном|всем|итоговом) (?:сочинении|тексте)|(?:готовая|полная|вся) работа|(?:готовое|полное|все) сочинение|(?:готовый|полный|весь|окончательный) текст) (?:(?:я насчитал[аи]?|я пересчитал[аи]?|у меня|ровно|всего|пока|получилось|вышло) )*(\d{1,6}) слов(?:о|а)?(?= |$)/u);
    const followup = previousTurn?.exam === true && /250 слов/u.test(previousTurn.assistant || '')
      ? words.match(/^(?:а |если |а если |ровно |всего )*(\d{1,6})(?: (?:хватит|достаточно))?$/u) : null;
    const fragmentOnly = /(?:только|лишь|один|одно|этот|мой) (?:план|тезис|вывод|вступление|абзац|фрагмент)|в (?:этом |одном |моем )?(?:плане|абзаце|тезисе|отрывке|фрагменте)|(?:абзац|фрагмент) (?:пока |всего |короче |на )?\d|(?:выделил|выделила) (?:только )?(?:вывод|абзац|фразу|фрагмент)|это (?:план|набросок плана)/u.test(words);
    const asksLength = /сколько (?:нужно |надо |должно быть )?слов|(?:хватит|достаточно|мало) (?:ли |мне )?слов|хватит ли (?:мне )?по объему|миним[а-я]* (?:объем|(?:количество )?слов)|(?:какой|каков|максимальн[а-я]*|рекомендуем[а-я]*|требовани[а-я]* к) объем|объем (?:итогового |моего )?(?:сочинения|текста|работы)|служебные слова|считаются ли (?:союзы|предлоги)/u.test(words);
    if (!quantity && !followup && !asksLength) return '';
    if (fragmentOnly && !fullQuantity) {
      return 'Для плана или отдельного абзаца минимума нет. Требование в 250 слов относится ко всему сочинению. ФИПИ рекомендует от 350 слов. Найди в абзаце поступок или деталь из книги. Как эта деталь помогает ответить на вопрос темы?';
    }
    const rules = 'Минимум для полного сочинения — 250 слов. ФИПИ рекомендует от 350. Служебные слова тоже считаются.';
    const number = fullQuantity || quantity || followup;
    const singleCount = !/\d+ (?:слов(?:а|о)? )?(?:или|и) (?:на )?\d+|не хватает|не достает|не дотягива|остал[оаи]сь (?:еще |написать |дописать )*\d|\d+ слов(?:о|а)? остал[оаи]сь|еще надо|добрать/u.test(words);
    const declared = number && singleCount ? Number(number[1]) : null;
    if (declared !== null && declared < 250) {
      return 'Если это вся работа и подсчёт верен, по требованию к объёму ставят «незачёт» за всё сочинение. ' + rules + ' Найди в черновике поступок героя и объясни, почему он подтверждает твою мысль.';
    }
    if (declared !== null && declared >= 350) {
      return rules + ' При таком объёме порог пройден. Теперь найди предложение, в котором ты объяснил, почему эпизод подтверждает твой ответ на тему.';
    }
    if (declared !== null) {
      return rules + ' При 250–349 словах требование к объёму выполнено. Для общего результата важны ещё самостоятельность и критерии. Перечитай, как ты связал эпизод с тезисом.';
    }
    const size = countWords(context.draft, context.draftHeading);
    return rules + ' Максимальный объём не установлен.' + (size ? ' В поле черновика сейчас примерно ' + size + ' (по счётчику тренажёра).' : '') + ' Проверь по счётчику весь черновик.';
  }

  function readingPerspective(context, raw) {
    const words = normalized(raw);
    const scriptureName = /(?:^| )(?:библи(?:я|и|ю|ей|ею)|евангели[а-я]+|к[оу]ран(?:а|у|ом|е)?|тор(?:а|ы|е|у|ой)|танах[а-я]*|бхагавад[а-я]* гит[а-я]*|священн[а-я]* (?:книг|писани|текст)[а-я]*)(?: |$)/u;
    const mentionsScripture = scriptureName.test(words);
    const sourceRequest = /подойдет|годится|засчитают|засчитыва|допустим|взять|привести|опереться|использовать|сослаться|ссылаться|цитировать|источник|(?:качестве|для|как) (?:литературн[а-я]* )?(?:примера?|аргумента?)|пример из|довод из/u;
    const asksPermission = /можно|допуска|разреш|достаточно|хватит|засч|подойдет|годится|могу ли|возьму|хочу (?:взять|использовать)/u;
    const required = /обязан[а-я]*|долж[а-я]*|обязательно|(?:надо|нужно) ли/u.test(words)
      && /брать|взять|приводить|привести|выбирать|выбрать|использовать|писать (?:именно )?о|опираться/u.test(words);
    const without = words.match(/(?:^| )без (.+)/u);
    const everydaySource = /(?:светск[а-я]*|обычн[а-я]*|библиотечн[а-я]*) (?:книг|произведени)|из библиотек|книг[а-я]* в библиотеке/u.test(words);
    const freeChoice = 'Ты сам выбираешь подходящий опубликованный текст. Подойдёт и светское произведение. Вспомни один фрагмент и объясни, как он подтверждает твою мысль по теме.';
    if ((required && (mentionsScripture || /религиозн[а-я]* (?:пример|аргумент)/u.test(words))) ||
        (without && without[1].search(scriptureName) === 0 && (asksPermission.test(words) || /хочу|обойдусь|буду писать/u.test(words))) ||
        (everydaySource && !mentionsScripture && asksPermission.test(words)) ||
        /(?:обязательно|нужно|надо) ли (?:мне )?верить в бога/u.test(words)) {
      return freeChoice;
    }
    const briefRequest = words.match(/^(?:а )?(?:можно(?: ли)?|могу ли взять|хочу взять) (?:мне )?(.+)/u);
    if (mentionsScripture && ((asksPermission.test(words) && sourceRequest.test(words)) ||
        (briefRequest && briefRequest[1].search(scriptureName) === 0))) {
      return 'Библию и другие священные книги религий мира ФИПИ допускает как литературный источник. Достаточно одного уместного примера. Назови текст, найди конкретный фрагмент в опубликованном издании и объясни своими словами, как он подтверждает твой ответ на тему.';
    }

    const mentionsBelief = /вероисповед|религи|убеждени|атеис|мусульман|иудаиз|буддис|(?:^| )вер[ауы](?: |$)/u.test(words);
    if (mentionsBelief && /(?:снимут|снизят|снижают|потеряю).*балл|незачет|повлияет ли.*оценк|оцен[ия].*(?:веру|убеждени|религи)/u.test(words)) {
      return 'В школьных критериях ФИПИ нет оценки за убеждения читателя. У тебя может быть собственная позиция. Покажи, какая деталь из выбранного текста помогает ответить на вопрос темы.';
    }

    const ownReading = 'Ты можешь предложить своё прочтение и спорить с предложенным утверждением. Какая деталь текста помогает тебе обосновать свою мысль по теме?';
    const requestsOwnPerspective = /(?:можно|хочу|разреш[а-я]*|могу ли)/u.test(words)
      && /(?:с (?:атеистическ|мусульманск|исламск|буддийск|христианск|иудейск)[а-я]* точки зрения|с позици[ий] (?:атеист|ислам|будди|мусульман|христиан|иудаиз)|в (?:другой|моей|своей|иной) традиции|(?:свое|собственное|иное|другое) (?:прочтение|толкование))/u.test(words);
    if (requestsOwnPerspective || (/(?:не соглашаться|не соглас[а-я]*|возражать|обязательно ли (?:соглашаться|разделять|верить)|долж[а-я]* ли (?:я )?(?:соглашаться|разделять|верить)|другой веры|атеистическ[а-я]* точк|по (?:своему|другому) (?:прочитать|понять|истолковать))/u.test(words)
        && /трактовк|толкован|прочтени|точк[аиу] зрени|вер[аиуы]|христиан|православ|автор|геро|формулировк|утверждени|традици|религи/u.test(words))) {
      return ownReading;
    }

    // A request applies to its own clause. A profession of faith or a description
    // of a character is not a request to change the workshop's questions.
    const clauses = raw.split(/[,;.!?]|(?:^|\s)(?:но|зато|а)(?=\s)/iu).map(normalized).filter(Boolean);
    const request = /^(?:(?:я|а|все таки|пожалуйста|тогда|теперь|лучше) )*(?:хочу|можно(?: ли)?|давай(?:те)?|прошу|включи|переключи|выбираю|попробуем|покажи|предпочитаю) (?:(?:я|мне|все же|рассмотреть|включить|выбрать|попробовать|перейти|переключиться|на|про|в|с|дать|пожалуйста) )*(православн[а-я]*|светск[а-я]*)(?: (?:прочтени[а-я]*|ракурс[а-я]*|комментари[а-я]*|взгляд[а-я]*|подход[а-я]*|уклон[а-я]*|разбор[а-я]*|подсказк[а-я]*|толковани[а-я]*|перспектив[а-я]*))?$/u;
    const decline = /^(?:(?:я|а|мне|лучше|пожалуйста|только|хочу|можно|ли|давай|давайте|давай читать|напишу|читать|разберем|попробуем|обойтись|работать|писать) )*(?:без |не (?:хочу|надо|нуж[а-я]+|предлагай|показывай) (?:мне )?(?:обсуждать )?)(?:религи[а-я]*|православ[а-я]*|христианск[а-я]*|вер[ыу])(?: |$)/u;
    for (const clause of clauses.reverse()) {
      const choice = clause.match(request);
      if (choice?.[1].startsWith('православн')) {
        return 'Можно выбрать православный комментарий к тексту в переключателе подсказок. ' + readingQuestion(context.work, 'orthodox');
      }
      if (choice || decline.test(clause)) {
        return 'Можно работать в светском ракурсе. В режиме «Литературный разбор» объясни поступок так, как ты его понимаешь. ' + readingQuestion(context.work, 'secular');
      }
    }

    const identityOnly = /^я (?:не )?(?:верующ[а-я]*|верю(?: в бога)?|православн[а-я]*|мусульман[а-я]*|иуде[йия]|буддист[а-я]*|атеист[а-я]*|агностик[а-я]*|католи[а-я]*|протестант[а-я]*|другой веры)$/u;
    if (identityOnly.test(words) || /(?:обязательно|нужно|надо) ли (?:мне )?(?:указывать|назвать|раскрывать|сообщать) (?:сво[а-я]* )?(?:веру|религи[а-я]*|убеждени[а-я]*)/u.test(words)) {
      return 'О своих убеждениях рассказывать необязательно. Для сочинения подойдёт знакомое тебе произведение. Какой эпизод ты хотел бы разобрать?';
    }
    return '';
  }

  function dialogueReply(context = {}, message = '', previousTurn = null) {
    const raw = String(message ?? '').trim();
    const words = normalized(raw);
    const stage = Object.hasOwn(stages, context.stage) ? context.stage : 'thesis';
    if (!words) return 'Напиши, на чём ты остановился. Можно прислать одну свою фразу или задать вопрос о сочинении.';
    if (/^(?:привет|здравствуй(?:те)?|добрый (?:день|вечер)|доброе утро)$/u.test(words)) {
      return 'Привет! Можешь принести одну фразу из своего черновика или спросить о сочинении.';
    }

    const asks = raw.includes('?') || /^(?:а |так |подскажи |скажи )*(?:можно|сколько|надо ли|нужно ли|обязательно ли|хватит|достаточно|правда ли|как|что|кто|почему|где|разве|како)/u.test(words);
    const previousUser = normalized(previousTurn?.user);
    const previousReply = String(previousTurn?.assistant ?? '');
    const repeated = words === previousUser || (previousUser && words === 'все еще ' + previousUser);

    const perspective = readingPerspective(context, raw);
    if (perspective) return perspective;

    if (/(?:дв[аеух]|два|две|втор|одн|один|количеств|сколько|\d+).*?(?:книг|книж|литературн|аргумент|пример|произведени|текст)|(?:книг|аргумент|произведени|пример).*?(?:дв[аеух]|сколько)/u.test(words) && (asks || /обязательн|требую|нуж(?:но|ны|на)|хватит/u.test(words))) {
      return 'Достаточно одного опубликованного произведения. Выбери из него эпизод, который действительно помогает обосновать твою мысль. ' + (repeated ? 'Какую сцену из этой книги ты лучше всего помнишь?' : 'Как поступок героя связан с темой?');
    }

    if (/(?:^| )тем(?:а|е|у|ы|ой)?(?: |$)/u.test(words) && /будут|попад[еу]|настоящие|реальные|заранее|на экзамене/u.test(words) && asks) {
      return 'В тренажёре авторские темы для практики. Конкретный комплект на экзамене станет известен в день проведения. Какой вопрос тебе хотелось бы обдумать на знакомой книге?';
    }
    if (/(?:^| )тем(?:а|е|у|ы|ой)?(?: |$)/u.test(words) && /сколько|все темы|одну тему|одной тем/u.test(words) && asks) {
      return 'На итоговом сочинении выбирают одну из шести предложенных тем. Прочитай формулировку целиком: какой вопрос ты будешь раскрывать?';
    }
    if (/(?:^| )тем(?:а|е|у|ы|ой)?(?: |$)/u.test(words) && /выбр|выбир|поня|разобр|смысл|о чем|кака[яю]|какую|что значит|что означает|что от меня/u.test(words) && asks) {
      if (/выбр|выбир/u.test(words)) {
        return 'Прочитай два вопроса из списка. Для какого ты можешь сразу назвать и свой ответ, и сцену из прочитанной книги? Возьми его для первой попытки.';
      }
      const title = context.topic ? 'Твоя тема — ' + excerpt(context.topic) + '. ' : 'Посмотри на формулировку выбранной темы. ';
      return title + 'Представь, что ты задаёшь этот вопрос другу. Какими словами ты бы его переформулировал?';
    }

    if (/тезис/u.test(words) && /что такое|что значит|это что/u.test(words)) {
      return 'Тезис — твой ответ на вопрос темы. Его предстоит обосновать. Как бы ты сформулировал своё мнение одним предложением?';
    }
    if (/зачет|оценк|проверь|сколько баллов/u.test(words) && (asks || /проверь|поставь|оцени/u.test(words))) {
      return 'Результат за экзаменационную работу определяет эксперт. Для самопроверки найди в черновике две фразы: свой ответ на тему и объяснение, почему эпизод его подтверждает. Пришли ту, в которой сомневаешься.';
    }

    // A statement of literary interpretation may be a student's answer, rather than a request.
    const unclearNeed = /^(?:(?:я|а|мне|пока|все еще|вообще|совсем|просто|никак) )*(?:не знаю|не понимаю|не получается|запутал[а-я]*|застрял[а-я]*|помоги|нужна помощь|что дальше|как дальше)(?: |$)/u.test(words);
    const asksForHelp = asks || unclearNeed || /^(?:покажи|объясни|подскажи|помоги)|помог|подска|не понимаю|не могу|не получа|застр|хоч|трудно|путаю|повторя|только пересказ|сомнева/u.test(words);
    const verifiesFact = /звали|зовут|дослов|в (?:какой|которой) главе|кто такой|кто такая|кто (?:именно |это )?сказал|не могу вспомнить,? как/u.test(words);
    if (asksForHelp && !verifiesFact && !repeated && typeof EssayIntent !== 'undefined') {
      const hint = intentFeedback(EssayIntent.classify(raw).label, context);
      if (hint && previousReply !== hint) return hint;
    }

    const aboutWriting = /черновик|сочинени|аргумент|рассужден|параграф|абзац|запися[хми]|свое[йм] фраз|написанн|моим текст|моем текст|моему текст|мой текст|моей мысл|свою мысл|у меня на листе/u.test(words);
    const outsideWriting = /расписани|регистрац|пароль|бланк|экзамен|сохран[ияе]|скачать|файл|принтер|где сдавать|оплат|войти|погода/u.test(words);
    if (asksForHelp && !verifiesFact && !outsideWriting && (aboutWriting || unclearNeed)) {
      return {assistant:'С чем нужна помощь в сочинении? Выбери одно действие для своей записи.', chooseIntent:true};
    }

    const recallsScene = asks || /не (?:помню|уверен|могу вспомнить)|забыл/u.test(words);
    const aboutSceneFact = /цитат|дословно|точн[аоя]|сказал|говорит|произнес|звали|зовут|поступил|поступила|пошел|заплакал|назва|действительно ли|правда ли|в (?:какой|которой) главе|^(?:а )?(?:кто|кому|когда|где|куда|зачем|почему|разве)|(?:какой|какая|какую|что) (?:геро|персонаж|автор)/u.test(words);
    if (!outsideWriting && (verifiesFact || (recallsScene && aboutSceneFact))) {
      const book = context.work?.title ? 'Открой полный текст произведения ' + excerpt(context.work.title) + '. ' : 'Уточни автора и название и открой полный текст выбранного произведения. ';
      return book + (repeated ? 'Прочитай пару предложений до и после спорного места. К кому относится фраза и что происходит сразу после неё?' : 'Найди нужную сцену, проверь, кому принадлежит реплика или поступок. Можно прислать короткий фрагмент с указанием источника или пересказать сцену своими словами.');
    }

    if (/^(?:(?:я|все еще|пока|вообще) )*(?:не знаю|не понимаю|затрудняюсь|застрял|растерял|не получается|помоги)|попроще|поподробнее|по другому/u.test(words)) {
      return repeated || previousReply ? smallerSteps[stage] : advise({...context, stage, reason:'stuck'});
    }
    if (repeated) return smallerSteps[stage];
    if (asks) {
      return 'Уточни, о чём вопрос: о правилах сочинения, о детали из книги или о формулировке твоей мысли? Можно привести одно предложение и указать, что именно в нём вызывает сомнение.';
    }

    const turns = conversationSteps[stage];
    const lastStep = turns.findIndex(step => previousReply.includes(step));
    const nextStep = turns[(lastStep + 1) % turns.length];
    return 'Возьмём твою фразу ' + excerpt(raw) + '. ' + nextStep;
  }

  function respond(context = {}, message = '', previousTurn = null) {
    const words = normalized(message);
    const wantsQuote = /(?:^| )(?:процитируй(?:те)?|можешь (?:ли )?процитировать|(?:дай|пришли|подбери|найди|приведи|покажи|нужна|нужны|можешь (?:дать|привести)) (?:(?:мне|одну|точн[а-я]*|коротк[а-я]*|подходящ[а-я]*) )*цитат[а-я]*)(?= |$)/u.test(words);
    if (wantsQuote) {
      return {assistant:'Открой издание, по которому читаешь, и сверь слова в самой сцене. Пришли короткий отрывок и укажи автора, название и главу или страницу. Тогда можно выбрать строку, которая подтверждает твою мысль. Если помнишь только событие, перескажи его своими словами без кавычек.'};
    }
    const guidance = examGuidance(context, words, previousTurn);
    if (guidance) return {assistant:guidance, exam:true};
    const result = dialogueReply(context, message, previousTurn);
    return typeof result === 'string' ? {assistant:result} : result;
  }

  function reply(context, message, previousTurn) {
    return respond(context, message, previousTurn).assistant;
  }

  return Object.freeze({advise, countWords, firstDraftLine, intentFeedback, reply, respond});
})();
