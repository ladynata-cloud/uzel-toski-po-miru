"""Continue training the published offline essay router (Python 3.10+ and Node.js)."""

import argparse
import hashlib
import json
import math
from pathlib import Path
import random
import re
import subprocess

HERE = Path(__file__).resolve().parent
EPOCHS = 18


def read_training_rows(path, labels):
    rows = json.loads(path.read_text(encoding="utf-8"))
    seen = set()
    for row in rows:
        normalized = " ".join(re.findall(r"[а-яa-z0-9]+", row["text"].lower().replace("ё", "е")))
        if not normalized or normalized in seen or row["label"] not in labels:
            raise ValueError("Invalid or duplicate training example")
        seen.add(normalized)
    if not rows or set(labels) != {row["label"] for row in rows}:
        raise ValueError("Training data must represent all router labels")
    return rows


def sample_vectors(runtime, rows, weights):
    # A single implementation of tokenization/phrase matching serves the trainer
    # and the student's browser. The examples are only passed to a local process.
    runner = runtime + """
const texts = JSON.parse(require('node:fs').readFileSync(0, 'utf8'));
process.stdout.write(JSON.stringify(texts.map(extract)));
"""
    result = subprocess.run(
        ["node", "-e", runner],
        input=json.dumps([row["text"] for row in rows], ensure_ascii=False),
        capture_output=True, text=True, encoding="utf-8", check=True,
    )
    vectors = []
    for example in json.loads(result.stdout):
        values = {key: weights[key][0] * amount / 100
                  for key, amount in example.items() if key in weights}
        norm = math.sqrt(sum(value * value for value in values.values())) or 1
        vectors.append({key: value / norm for key, value in values.items()})
    return vectors


def fit(seed, rows, vectors):
    labels = seed["labels"]
    class_count = len(labels)
    weights = {key: [value / 100 for value in row[1:]] for key, row in seed["weights"].items()}
    intercept = [value / 1000 for value in seed["intercept"]]
    targets = [labels.index(row["label"]) for row in rows]

    # Multinomial logistic regression, initialized from the actual published
    # weights and fixed IDFs. Replaying older requests limits forgetting.
    for epoch in range(EPOCHS):
        order = list(range(len(rows)))
        random.Random(781 + epoch).shuffle(order)
        learning_rate = .025 / (1 + epoch * .10)
        for index in order:
            features = vectors[index]
            logits = intercept.copy()
            for key, value in features.items():
                for j in range(class_count):
                    logits[j] += weights[key][j] * value
            largest = max(logits)
            exp = [math.exp(score - largest) for score in logits]
            total = sum(exp)
            step = [learning_rate * ((j == targets[index]) - e / total) for j, e in enumerate(exp)]
            for j in range(class_count):
                intercept[j] += step[j]
            for key, value in features.items():
                for j in range(class_count):
                    weights[key][j] += step[j] * value

    packed = {key: [seed["weights"][key][0], *[round(w * 100) for w in values]]
              for key, values in weights.items()}
    return {"labels": labels, "weights": packed, "intercept": [round(v * 1000) for v in intercept]}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=HERE / "intent-training.json")
    parser.add_argument("--out", type=Path, default=HERE.parent / "intent-model.js")
    args = parser.parse_args()
    seed = json.loads((HERE / "intent-seed-2026-11-20.json").read_text(encoding="utf-8"))
    runtime = (HERE / "intent-runtime.js").read_text(encoding="utf-8")
    rows = read_training_rows(args.input, seed["labels"])
    parameters = fit(seed, rows, sample_vectors(runtime, rows, seed["weights"]))
    data = json.dumps(parameters, ensure_ascii=False, separators=(",", ":"))
    source = ("// Generated by assistant/train_intents.py. Scoring takes place on the device.\n"
              "const EssayIntent = (() => {\n" + runtime + "\nreturn createEssayIntent(" + data + ");\n})();\n")
    args.out.write_text(source, encoding="utf-8")
    print(f"examples={len(rows)} features={len(parameters['weights'])} epochs={EPOCHS}")
    print("SHA256", hashlib.sha256(source.encode()).hexdigest())


if __name__ == "__main__":
    main()
