def revise_workshop_quotes(lessons):
    for lesson in lessons:
        choice = WORKSHOP_QUOTES.get(lesson['slug'])
        if choice is None:
            continue
        quote_id, comment = choice
        lesson['tradition'] = (
            quote_block(quote_id)
            + '<p><strong>Комментарий мастерской.</strong> '
            + escape(comment) + '</p>'
        )
        scripture = SCRIPTURE_LINKS.get(lesson['slug'])
        if scripture:
            url, label = scripture
            lesson['tradition'] += (
                '<p class="fine">Для сопоставления: '
                f'<a href="{escape(url, quote=True)}">{escape(label)}</a>.</p>'
            )
