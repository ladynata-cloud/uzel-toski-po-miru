def _quotation_with_comment(quote_id, note=None):
    markup = quote_block(quote_id)
    if note:
        markup += '<p><strong>Комментарий мастерской.</strong> ' + escape(note) + '</p>'
    return markup


def workshop_tradition(key, original):
    """Show the approved quotation at the point where a workshop discusses it."""
    if key in LINK_ONLY_WORKSHOP_QUOTES:
        quote_id = LINK_ONLY_WORKSHOP_QUOTES[key]
        pattern = (
            r'<p>(?:(?!</p>).)*?href="/tsitaty/#' + re.escape(quote_id)
            + r'"(?:(?!</p>).)*?</p>'
        )
        replacement = _quotation_with_comment(quote_id, LINK_REPLACEMENT_COMMENTS.get(key))
        updated, count = re.subn(pattern, lambda match: replacement, original, count=1, flags=re.S)
        if count != 1:
            raise ValueError(f'Expected one legacy quotation paragraph in workshop {key}')
        return updated
    if key in WORKSHOP_QUOTES:
        return original + '<aside class="context-note">' + _quotation_with_comment(*WORKSHOP_QUOTES[key]) + '</aside>'
    return original


def article_dialogue(path):
    """Keep the article's literary analysis before its explicitly editorial comparison."""
    if path not in ARTICLE_QUOTES:
        return ''
    return (
        '<section id="tradition"><h2>Православный вопрос к тексту</h2>'
        + _quotation_with_comment(*ARTICLE_QUOTES[path]) + '</section>'
    )
