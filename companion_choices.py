"""Editorial choices: cultural context and listening after a literary text."""

CAUCASUS = {
    'tolstoy-nabeg': ('gelati-mosaic', 'greek-bridegroom'),
    'tolstoy-rubka-lesa': ('shoana-church', 'serbian-pascha'),
    'tolstoy-razhalovanny': ('armenian-evangelists', 'allegri-miserere'),
    'senior-045': ('armenian-john', 'cello'),
    'tolstoy-hadzhi-murat': ('gagarin-hadji-murat', 'armenian-light'),
}


def caucasus_companions(essay):
    from art_library import ART_LIBRARY
    from music import MUSIC
    art, music = CAUCASUS[essay['slug']]
    essay['art'] = art
    essay['art_note'] = ART_LIBRARY[art]['relation']
    if art == 'armenian-john':
        essay['art_note'] += ' Станица в «Казаках» не названа армянской: рукопись выбрана для знакомства с разнообразием христианского Кавказа.'
    essay['music'] = music
    essay['music_note'] = next(m['context'] for m in MUSIC if m['id'] == music) if music != 'cello' else 'Сарабанда из Первой виолончельной сюиты Баха — инструментальная пауза после чтения. У этой музыки нет программы о Кавказе или героях Толстого.'
    essay['textual_basis'] = [dict(label='Глава / раздел ' + s['chapter'], url=s['url'], detail=s['verified_detail']) for s in essay.get('source_review', [])]


